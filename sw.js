// Service worker do Trastes — permite abrir o app offline depois da 1ª visita.
// Precisa estar hospedado num servidor real com HTTPS (ou localhost) para funcionar;
// não funciona quando o HTML é aberto direto do disco (file://) nem dentro do
// preview de artifacts do Claude.ai.
const CACHE_NAME = 'trastes-v1';
const APP_SHELL = ['./index.html', './manifest.json', './icon-192.png', './icon-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n)))
    )
  );
  self.clients.claim();
});

// Estratégia "cache primeiro, rede como reserva": o app abre instantaneamente
// mesmo offline, e atualiza o cache silenciosamente quando há internet.
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((res) => {
          if (res && res.status === 200) {
            const clone = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
